// Standalone test for the capture decision. No pasteboard: types are strings, images are counts.
import Foundation

@main
@MainActor
struct CapturePolicyTests {
    static var failures = 0
    static var passes = 0

    private static let plainText = "public.utf8-plain-text"

    static func main() {
        markedCopiesAreNeverRecorded()
        ourOwnPasteBackIsNotRecaptured()
        emptyTextIsSkipped()
        textCapIsAByteCount()
        imageTypeOrderPrefersCompressed()
        imageBudgetIsEnforced()
        typesWithNoStorableContentAreSkipped()

        print("\(passes)/\(passes + failures) passed")
        if failures > 0 { exit(1) }
    }

    // MARK: - Cases

    /// A missed marker is a password in history — the one failure mode with no recovery.
    static func markedCopiesAreNeverRecorded() {
        let markers = [
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType",
            "de.petermaurer.TransientPasteboardType",
            "com.typeit4me.clipping",
            "Pasteboard generator type",
            "PasswordPboardType",
            "com.agilebits.onepassword",
            "net.antelle.keeweb"
        ]
        for marker in markers {
            expect(
                decide(types: [plainText, marker], text: "hunter2") == .skip,
                "\(marker) suppresses the copy")
            expect(CapturePolicy.isSkipped(types: [marker]), "\(marker) is on the skip list")
        }
        // Folklore, dropped deliberately: no primary source, and people mean ConcealedType.
        expect(
            !CapturePolicy.isSkipped(types: ["com.apple.is-sensitive"]),
            "com.apple.is-sensitive is not a marker we honour")
        expect(
            decide(types: [plainText], text: "hello") == .text("hello"),
            "an unmarked text copy is kept as text")
    }

    /// Without this the paster's own write would re-enter history on the next poll.
    static func ourOwnPasteBackIsNotRecaptured() {
        expect(
            decide(types: [plainText, CapturePolicy.internalType], text: "echo") == .skip,
            "our marker suppresses the copy")
        expect(
            CapturePolicy.internalType == "app.spare.internal",
            "the marker is the constant the monitor and paster share")
    }

    static func emptyTextIsSkipped() {
        expect(
            decide(types: [plainText], text: "   \n") == .skip, "whitespace-only text is skipped")
        expect(decide(types: [plainText], text: "") == .skip, "empty text is skipped")
        expect(
            decide(types: [plainText], text: " keep me ") == .text(" keep me "),
            "text with content is kept verbatim, trimmed only for the emptiness check")
    }

    /// The cap is a byte count so a multi-MB copy costs one O(1) check, not a grapheme walk.
    static func textCapIsAByteCount() {
        let limit = CapturePolicy.textByteLimit
        let exact = String(repeating: "a", count: limit)
        expect(exact.utf8.count == limit, "the fixture is exactly at the cap")
        expect(decide(types: [plainText], text: exact) == .text(exact), "128 KB exactly is kept")
        expect(decide(types: [plainText], text: exact + "a") == .skip, "one byte over is skipped")

        // A multi-byte scalar is over the cap by bytes while still under it by character count.
        let wide = String(repeating: "é", count: limit / 2) + "é"
        expect(wide.count < limit, "the fixture is under the cap by character count")
        expect(decide(types: [plainText], text: wide) == .skip, "but over it by UTF-8 bytes")
    }

    static func imageTypeOrderPrefersCompressed() {
        expect(
            decide(types: ["public.tiff"], text: nil, imageByteCount: 1024)
                == .image(uti: "public.tiff", needsTranscode: true),
            "a TIFF-only copy is captured, on the transcode path")
        expect(
            decide(types: ["public.png", "public.tiff"], text: nil, imageByteCount: 1024)
                == .image(uti: "public.png", needsTranscode: false),
            "PNG wins over TIFF, and needs no transcode")
        expect(
            decide(types: ["public.tiff", "public.jpeg"], text: nil, imageByteCount: 1024)
                == .image(uti: "public.jpeg", needsTranscode: false),
            "order comes from the policy, not from the pasteboard's listing order")
        expect(
            CapturePolicy.imageType(in: ["public.tiff", "public.heic", "com.compuserve.gif"])
                == "public.heic",
            "HEIC outranks GIF and TIFF")
        expect(
            CapturePolicy.imageTypes.last == "public.tiff",
            "TIFF is last because it is the uncompressed one")
    }

    static func imageBudgetIsEnforced() {
        let budget = CapturePolicy.imageByteBudget
        expect(budget == 32 * 1024 * 1024, "the per-image budget is 32 MB")
        expect(
            decide(types: ["public.png"], text: nil, imageByteCount: budget)
                == .image(uti: "public.png", needsTranscode: false),
            "an image exactly at the budget is captured")
        expect(
            decide(types: ["public.png"], text: nil, imageByteCount: budget + 1) == .skip,
            "one byte over the budget is skipped")
        expect(
            decide(types: ["public.png"], text: nil, imageByteCount: 0) == .skip,
            "an empty image payload is skipped")
        expect(
            decide(types: ["public.png"], text: nil, imageByteCount: nil) == .skip,
            "an image type with no payload is skipped")
    }

    static func typesWithNoStorableContentAreSkipped() {
        expect(decide(types: ["dyn.abc"], text: nil) == .skip, "a dyn. type names nothing storable")
        expect(CapturePolicy.imageType(in: ["dyn.public.png"]) == nil, "dyn. never nominates")
        expect(
            CapturePolicy.imageType(in: ["com.microsoft.ole.source.xyz"]) == nil,
            "an OLE source type never nominates")
        expect(decide(types: [], text: nil) == .skip, "an empty type set is skipped")
        expect(
            decide(types: ["public.file-url"], text: nil, imageByteCount: 1024) == .skip,
            "a type we do not store is skipped even with bytes on offer")
    }

    // MARK: - Helpers

    static func decide(
        types: [String], text: String?, imageByteCount: Int? = nil
    ) -> CapturePolicy.Decision {
        CapturePolicy.decide(types: types, text: text, imageByteCount: imageByteCount)
    }

    static func expect(
        _ condition: Bool, _ label: String, fileID: String = #fileID, line: Int = #line
    ) {
        if condition {
            passes += 1
        } else {
            print("FAIL: \(label) (\(fileID):\(line))")
            failures += 1
        }
    }
}
