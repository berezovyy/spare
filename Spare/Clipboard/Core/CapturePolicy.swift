import Foundation

/// What a copy becomes. The monitor watches and reads; this decides, on values alone.
enum CapturePolicy {
    /// Attached when *we* write the pasteboard, so a paste-back never re-enters history.
    static let internalType = "app.spare.internal"

    /// One O(1) byte check. Not `text.count`, which walks graphemes across a huge copy.
    static let textByteLimit = 128_768

    /// A single copy bigger than this is a document, not a clip worth keeping.
    static let imageByteBudget = 32 * 1024 * 1024

    /// Compressed first, TIFF last: it is uncompressed, so it is the only one worth transcoding.
    static let imageTypes = [
        "public.png", "public.heic", "public.jpeg", "com.compuserve.gif", "public.tiff"
    ]

    /// Markers put on a copy that must not be recorded, by password managers, apps and the OS.
    /// No `com.apple.is-sensitive`: it has no primary source, and people mean `ConcealedType`.
    static let skippedTypes: Set<String> = [
        internalType,
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "PasswordPboardType",
        "com.agilebits.onepassword",
        "net.antelle.keeweb"
    ]

    /// Dynamic and OLE types name no content we can store, so they never nominate a payload.
    private static let droppedPrefixes = ["dyn.", "com.microsoft.ole.source."]

    enum Decision: Equatable, Sendable {
        case skip
        case text(String)
        /// `needsTranscode` is TIFF only; the transcode itself belongs to the monitor.
        case image(uti: String, needsTranscode: Bool)
    }

    /// `types` is the *root* type set, read before any content: `NSPasteboard.types` advertises
    /// types the item does not actually carry (Maccy #241), so filtering must happen up here.
    static func decide(types: [String], text: String?, imageByteCount: Int?) -> Decision {
        guard !isSkipped(types: types) else { return .skip }

        if let text {
            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !trimmed.isEmpty, text.utf8.count <= textByteLimit else { return .skip }
            return .text(text)
        }

        guard let uti = imageType(in: types) else { return .skip }
        guard let imageByteCount, imageByteCount > 0, imageByteCount <= imageByteBudget else {
            return .skip
        }
        return .image(uti: uti, needsTranscode: uti == "public.tiff")
    }

    /// True when the root type set carries a marker that forbids recording the copy at all.
    static func isSkipped(types: [String]) -> Bool {
        !Set(types).isDisjoint(with: skippedTypes)
    }

    /// The best image type on offer: compressed before TIFF, and never a dropped prefix.
    static func imageType(in types: [String]) -> String? {
        let offered = Set(
            types.filter { candidate in
                !droppedPrefixes.contains(where: candidate.hasPrefix)
            })
        return imageTypes.first(where: offered.contains)
    }
}
